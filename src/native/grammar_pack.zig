//! Build tool: `grammar-pack OUT FILE...` minifies each grammar JSON file
//! into OUT under its own name and writes `OUT/sources.zig`, which embeds
//! them in the order given (grammars.zig's) and lists, for each, the other
//! bundled grammars it includes, so a language loads only what it reaches.
//!
//! Each grammar's `injectTo` becomes the root scopes whose `injections` in
//! grammars.zig name it, the only roots it injects into, as vscode-textmate's
//! `getInjections` gives them; syntaxmate reads injections from that key.

const std = @import("std");
const grammars = @import("grammars.zig");

pub fn main(init: std.process.Init) !void {
    const arena = init.arena.allocator();
    const io = init.io;
    const args = try init.minimal.args.toSlice(arena);
    if (args.len < 2) return error.Usage;
    const paths = args[2..];
    if (paths.len != grammars.grammars.len) return error.GrammarCount;
    const cwd = std.Io.Dir.cwd();
    var out = try cwd.createDirPathOpen(io, args[1], .{});
    defer out.close(io);
    var index: std.ArrayList(u8) = .empty;
    try index.appendSlice(arena, "// Generated by src/native/grammar_pack.zig.\n\n/// Each grammar's JSON, minified.\npub const files = [_][]const u8{\n");
    var dependencies: std.ArrayList(u8) = .empty;
    try dependencies.appendSlice(arena, "/// The other grammars each one includes, by `Language` index.\npub const dependencies = [_][]const u16{\n");
    for (paths, 0..) |path, i| {
        const text = try cwd.readFileAlloc(io, path, arena, .limited(16 * 1024 * 1024));
        var value = try std.json.parseFromSliceLeaky(std.json.Value, arena, text, .{});
        if (value != .object) return error.NotAGrammar;
        var targets: std.json.Array = .init(arena);
        for (grammars.grammars) |root| for (root.injections) |injected| {
            if (@intFromEnum(injected) == i) try targets.append(.{ .string = root.scope });
        };
        _ = value.object.orderedRemove("injectTo");
        if (targets.items.len > 0) try value.object.put(arena, "injectTo", .{ .array = targets });
        const compact = try std.json.Stringify.valueAlloc(arena, value, .{});
        const file = std.fs.path.basename(path);
        try out.writeFile(io, .{ .sub_path = file, .data = compact });
        try index.print(arena, "    @embedFile(\"{s}\"),\n", .{file});

        var reached: std.AutoArrayHashMapUnmanaged(u16, void) = .empty;
        try collectIncludes(arena, value, &reached);
        _ = reached.swapRemove(@intCast(i));
        try dependencies.appendSlice(arena, "    &.{");
        for (reached.keys(), 0..) |dependency, k| try dependencies.print(arena, "{s}{d}", .{ if (k == 0) " " else ", ", dependency });
        try dependencies.appendSlice(arena, if (reached.count() > 0) " },\n" else "},\n");
    }
    try index.appendSlice(arena, "};\n\n");
    try dependencies.appendSlice(arena, "};\n");
    try index.appendSlice(arena, dependencies.items);
    try out.writeFile(io, .{ .sub_path = "sources.zig", .data = index.items });
}

/// Adds the bundled grammar behind every `"include": "scope"` or
/// `"scope#rule"` in `value`.
fn collectIncludes(arena: std.mem.Allocator, value: std.json.Value, reached: *std.AutoArrayHashMapUnmanaged(u16, void)) !void {
    switch (value) {
        .object => |object| {
            var it = object.iterator();
            while (it.next()) |entry| {
                if (std.mem.eql(u8, entry.key_ptr.*, "include") and entry.value_ptr.* == .string) {
                    const include = entry.value_ptr.string;
                    if (include.len == 0 or include[0] == '#' or include[0] == '$') continue;
                    const scope = include[0 .. std.mem.indexOfScalar(u8, include, '#') orelse include.len];
                    for (grammars.grammars, 0..) |grammar, k| {
                        if (std.mem.eql(u8, grammar.scope, scope)) try reached.put(arena, @intCast(k), {});
                    }
                } else try collectIncludes(arena, entry.value_ptr.*, reached);
            }
        },
        .array => |array| for (array.items) |item| try collectIncludes(arena, item, reached),
        else => {},
    }
}
