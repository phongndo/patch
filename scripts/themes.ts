// Lists Pierre Highlights' themes with the few colors the page needs to paint
// its own chrome (the diff loads each theme's full syntax colors itself).
import { readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

const dir = join(import.meta.dir, "..", "node_modules", "@pierre", "highlights", "dist", "themes");
const names = (await readdir(dir))
  .filter((f) => f.endsWith(".js") && !f.startsWith("loader"))
  .map((f) => f.slice(0, -3));

type Style = Record<string, unknown>;
const rows: string[] = [];
for (const id of names.sort()) {
  const theme = (await import(join(dir, `${id}.js`))).default as {
    name: string;
    appearance: string;
    style: Style;
  };
  const s = theme.style;
  const color = (...keys: string[]) =>
    keys.map((key) => s[key]).find((value) => typeof value === "string") as string;
  const entry = {
    id,
    name: theme.name,
    dark: theme.appearance === "dark",
    colors: {
      editor: color("editor.background", "background"),
      chrome: color("background", "editor.background"),
      text: color("editor.foreground", "text"),
      line: color("editor.active_line.background") ?? null,
      add: color("created") ?? null,
      del: color("deleted") ?? null,
      accent: color("modified", "info") ?? null,
    },
    // The eight terminal colors: the palette the theme tiles show as dots.
    palette: ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"]
      .map((name) => s[`terminal.ansi.${name}`])
      .filter((value): value is string => typeof value === "string"),
  };
  rows.push(`  ${JSON.stringify(entry)},`);
}
await writeFile(
  join(import.meta.dir, "..", "web", "themes.gen.ts"),
  `// Generated by scripts/themes.ts from @pierre/highlights.\nexport interface Theme {\n  id: string;\n  name: string;\n  dark: boolean;\n  colors: { editor: string; chrome: string; text: string; line: string | null; add: string | null; del: string | null; accent: string | null };\n  palette: string[];\n}\n\nexport const themes: Theme[] = [\n${rows.join("\n")}\n];\n`,
);
console.error(`${rows.length} themes`);
