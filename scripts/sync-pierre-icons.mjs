import { readFile, writeFile, mkdir, copyFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const icons = {
  help: "IconQuestion",
  more: "IconEllipsis",
  chevron: "IconChevron",
  folder: "IconFolderOpen",
  file: "IconFile",
  branch: "IconBranch",
  search: "IconSearch",
  split: "IconDiffSplit",
  unified: "IconDiffUnified",
  check: "IconCheck",
  checkbox: "IconCheckbox",
  comment: "IconComment",
  add: "IconCommentAdd",
  refresh: "IconRefresh",
  copy: "IconCopy",
  export: "IconFileExport",
  close: "IconX",
  left: "IconArrowLeftBar",
  right: "IconArrowRightShort",
  sidebar: "IconSidebarLeft",
  modified: "IconDiffModified",
  plus: "IconPlus",
  trash: "IconTrash",
  gear: "IconGear",
};
await mkdir(new URL("src/native/icons/", root), { recursive: true });
for (const [name, source] of Object.entries(icons)) {
  const svg = await readFile(new URL(`node_modules/@pierre/icons/svg/${source}.svg`, root), "utf8");
  await writeFile(
    new URL(`src/native/icons/${name}.svg`, root),
    svg
      .replaceAll('fill="black"', 'fill="currentColor"')
      .replaceAll('stroke="black"', 'stroke="currentColor"'),
  );
}
await copyFile(
  new URL("node_modules/@pierre/icons/LICENSE", root),
  new URL("src/native/icons/LICENSE", root),
);
// Drawn for Patch in the same 16px outline style; Pierre has no equivalent.
const local = [
  "command",
  "find",
  "repository",
  "document",
  "columns",
  "rows",
  "expanded",
  "collapsed",
  "blank",
  "swap",
  "note",
  "corner-tl",
  "corner-tr",
  "corner-bl",
  "corner-br",
];
const entries = [...Object.keys(icons), ...local]
  .map((name) => `    entry("${name}", "icons/${name}.svg"),`)
  .join("\n");
await writeFile(
  new URL("src/native/icons.zig", root),
  `// Pierre Icons 0.9.0, Apache-2.0. Generated by scripts/sync-pierre-icons.mjs.\nconst canvas = @import("native_sdk").canvas;\nfn entry(comptime name: []const u8, comptime source: []const u8) canvas.icons.Entry {\n    const icon = canvas.svg_icon.parseComptime(@embedFile(source));\n    return .{ .name = name, .icon = &icon };\n}\npub const all = [_]canvas.icons.Entry{\n${entries}\n};\n`,
);
