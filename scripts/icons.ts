// Copies the few Pierre icons the page uses into web/icons.gen.ts, so the
// bundle carries only these and not the whole set.
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const names = [
  "Branch",
  "TextBold",
  "Key",
  "ListOrdered",
  "Type",
  "Brush",
  "BrandGithub",
  "Merged",
  "Check",
  "CheckCircle",
  "ChevronSm",
  "Chevrons",
  "ChevronsClose",
  "Code",
  "Commit",
  "Comment",
  "CodeSearch",
  "DiffAdd",
  "DiffDeleted",
  "DiffModified",
  "DiffRenamed",
  "DiffSplit",
  "DiffUnified",
  "Eye",
  "FileText",
  "FileTree",
  "Filter",
  "Folder",
  "Gear",
  "Pencil",
  "Plus",
  "Question",
  "Refresh",
  "Search",
  "SidebarLeft",
  "Trash",
  "X",
];
const dir = join(import.meta.dir, "..", "node_modules", "@pierre", "icons", "svg");
const out = ["// Generated by scripts/icons.ts from @pierre/icons (Apache-2.0).", "export const icons = {"];
for (const name of names) {
  const svg = (await readFile(join(dir, `Icon${name}.svg`), "utf8"))
    .replace(/fill="(black|#000000|#000)"/g, 'fill="currentColor"')
    .replace(/\s*\n\s*/g, "")
    .replace(/ width="16" height="16"/, ' width="16" height="16" aria-hidden="true"');
  out.push(`  ${name[0]!.toLowerCase()}${name.slice(1)}: ${JSON.stringify(svg)},`);
}
// Pierre has no ⌘, so this one is drawn at its weight.
const command =
  '<svg width="16" height="16" aria-hidden="true" viewBox="0 0 16 16" fill="none" xmlns="http://www.w3.org/2000/svg"><path d="M10 4v8a2 2 0 1 0 2-2H4a2 2 0 1 0 2 2V4a2 2 0 1 0-2 2h8a2 2 0 1 0-2-2Z" stroke="currentColor" stroke-width="1.5" stroke-linejoin="round"/></svg>';
out.push(`  command: ${JSON.stringify(command)},`);
out.push("} as const;", "", "export type IconName = keyof typeof icons;", "");
await writeFile(join(import.meta.dir, "..", "web", "icons.gen.ts"), out.join("\n"));
